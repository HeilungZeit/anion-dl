/**
 * Факты о манифестах Kodik, общие для плеера и загрузчика.
 *
 * Лежат в листовом модуле без зависимостей намеренно: их нужно и
 * `DownloadService`, и плееру, а импортировать ради константы целый сервис с
 * плагинами — лишняя связь.
 */

/**
 * Что реально встречается у Kodik, от лучшего к худшему.
 *
 * 1080p сюда не входит: у Kodik его почти никогда нет, а на живых манифестах
 * он наблюдался как 404 при рабочих 720 и 480. Предлагать его в меню — значит
 * обещать то, чего нет, и молча скатываться на 720.
 */
export const QUALITIES = [720, 480, 360] as const;

export const DEFAULT_QUALITY = 720;

/**
 * Качество, зашитое в имя манифеста.
 *
 * Единственный честный источник: ключи в ответе эндпоинта Kodik с содержимым
 * расходятся — у `links["720"]` наблюдался URL с `480` в имени файла. Та же
 * причина, по которой `resolver.rs::upgrade_quality` сверяет имя, а не ключ.
 */
const QUALITY_IN_NAME = /(\d+)\.mp4:hls:/;

export function qualityOf(manifestUrl: string): number | null {
  const digits = QUALITY_IN_NAME.exec(manifestUrl)?.[1];
  return digits ? Number(digits) : null;
}
